#!/usr/bin/env bash
# Vendors the cart script `archival run` serves at /_archival/cart.js.
#
# A deployed site that takes payments serves the script from the hosting
# service, which builds it from site-dispatcher/src/client/cart.ts in
# jesseditson/archival-editor. A local run has to serve the same bytes, and a
# crate has to contain what it embeds, so the built script is committed here
# rather than fetched at build time.
#
# Usage: ./update-cart.sh <built cart.js, or the url of a deployed site's /_archival/cart.js> [where it was built from]
set -euo pipefail

SOURCE="${1:?usage: update-cart.sh <file or url> [where it was built from]}"
BUILT_FROM="${2:-${SOURCE}}"
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/src/binary/carriers/cart.js"

WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

case "${SOURCE}" in
  http://*|https://*) curl --fail --silent --show-error --location "${SOURCE}" > "${WORK}/cart.js" ;;
  *) cp "${SOURCE}" "${WORK}/cart.js" ;;
esac
grep -q "archivalCart" "${WORK}/cart.js" || {
  echo "${SOURCE} is not the cart script" >&2
  exit 1
}

{
  echo "// Generated by update-cart.sh -- do not edit by hand."
  echo "// ${BUILT_FROM}"
  cat "${WORK}/cart.js"
  echo
} > "${OUT}"

echo "Wrote ${OUT} from ${BUILT_FROM}"
